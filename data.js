// ─── 构建 CHARS 数组（去重并分配 dayIndex）────
const CHARS = [];
const seen = new Set();
RAW.forEach(row => {
  const [char, pinyin, pc, c1, c2, c3, sentence] = row;
  const key = char + pinyin;
  if (seen.has(key)) return;
  seen.add(key);
  const partIdx = parseInt(pc.match(/P(\d+)/)[1], 10) - 1;
  const catIdx  = parseInt(pc.match(/C(\d+)/)[1], 10);
  CHARS.push({
    char, pinyin,
    part: PARTS[partIdx].name,
    category: PARTS[partIdx].cats[catIdx],
    partIdx, catIdx,
    compounds: [c1, c2, c3].filter(Boolean),
    sentence
  });
});

// 分配 dayIndex 严格 10 字/天，最后一天可能不足
const PER_DAY = 10;
CHARS.forEach((c, i) => {
  c.dayIndex = Math.floor(i / PER_DAY);
});
const TOTAL_DAYS = Math.ceil(CHARS.length / PER_DAY);

// 导出到全局
window.CHARS = CHARS;
window.PARTS = PARTS;
window.TOTAL_DAYS = TOTAL_DAYS;
window.PER_DAY = PER_DAY;
